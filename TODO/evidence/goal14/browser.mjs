import assert from 'node:assert/strict';
import { writeFile } from 'node:fs/promises';
import { chromium } from '/tmp/kostolany-goal8-browser/node_modules/playwright-core/index.mjs';

const directory = new URL('./', import.meta.url).pathname;
const browser = await chromium.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true });
const page = await browser.newPage({ viewport: { width: 390, height: 844 } });
const errors = [];
const checkpoints = [];
page.on('pageerror', (error) => errors.push(error.message));
page.on('console', (message) => { if (message.type() === 'error') errors.push(message.text()); });
const click = (name, role = 'button') => page.getByRole(role, { name, exact: true }).click();
const capture = async (name) => {
  await page.screenshot({ path: `${directory}${name}.png` });
  checkpoints.push(name);
};
try {
  await page.goto('http://localhost:8081');
  await page.getByRole('button', { name: /^금리가 오르면/ }).waitFor();
  await capture('home');
  await click('인기', 'tab');
  await page.getByRole('button', { name: /^현금을/ }).waitFor();
  await click('탐색', 'tab');
  await click('기사 검색 열기');
  await page.getByRole('textbox', { name: '기사 검색어' }).fill('금리');
  await page.getByRole('button', { name: /^금리가 오르면/ }).waitFor();
  await capture('search');
  await page.getByRole('button', { name: /^금리가 오르면/ }).click();
  await page.getByRole('heading', { name: '사실 요약', exact: true }).waitFor();
  await click('초등학생', 'radio');
  await page.getByRole('heading', { name: '초등학생 수준 설명' }).waitFor();
  await page.getByRole('heading', { name: '이해를 돕는 예시' }).waitFor();
  await capture('article');
  await page.getByRole('button', { name: /^좋아요,.*로그인 필요$/ }).click();
  await click('로그인 닫기');
  await page.getByRole('button', { name: /^좋아요,.*로그인 필요$/ }).click();
  await click('Google로 로그인 (모의)');
  await page.getByRole('button', { name: /^좋아요,.*선택 안 됨$/ }).click();
  await page.getByRole('button', { name: /^좋아요,.*선택됨$/ }).waitFor();
  await page.getByRole('button', { name: /^북마크,.*저장 안 됨$/ }).click();
  await page.getByRole('button', { name: /^북마크,.*저장됨$/ }).waitFor();
  await click('탐색으로 돌아가기');
  assert.equal(await page.getByRole('textbox', { name: '기사 검색어' }).inputValue(), '금리');
  await click('라이브러리', 'tab');
  await click('읽기 목록 열기, 저장한 기사 1개');
  await page.getByRole('button', { name: /^금리가 오르면/ }).waitFor();
  await capture('reading-list');
  await click('프로필', 'tab');
  await click('프로필 편집');
  await page.getByRole('textbox', { name: '이름 · 필수' }).fill('검토 독자');
  await click('프로필 편집 취소');
  await page.getByRole('heading', { name: '예시 독자 A', exact: true }).waitFor();
  await click('설정 열기');
  await click('기본 설명 수준 변경');
  await click('중학생 기본 수준', 'radio');
  await click('기본 수준 저장');
  await page.getByText('현재 기본값 · 중학생', { exact: true }).waitFor();
  await capture('settings');
  await click('로그아웃');
  await click('로그아웃 취소');
  await click('로그아웃');
  await click('로그아웃 확인');
  await page.getByRole('button', { name: '모의 로그인 시작' }).waitFor();
  await click('홈', 'tab');
  await page.setViewportSize({ width: 320, height: 740 });
  await capture('home-320');
  await page.setViewportSize({ width: 1365, height: 900 });
  await capture('home-desktop');
  assert.deepEqual(errors, []);
  console.log(JSON.stringify({ status: 'passed', checkpoints, errors }, null, 2));
} catch (error) {
  await capture('failed');
  await writeFile(`${directory}failed.txt`, await page.locator('body').innerText());
  throw error;
} finally {
  await browser.close();
}
