import assert from 'node:assert/strict';
import {writeFile} from 'node:fs/promises';
import {chromium} from '/tmp/kostolany-goal8-browser/node_modules/playwright-core/index.mjs';
const out=new URL('./',import.meta.url).pathname;
const browser=await chromium.launch({executablePath:'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',headless:true});
const page=await browser.newPage({viewport:{width:393,height:759}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));page.on('console',m=>{if(m.type()==='error')errors.push(m.text())});
await page.goto('http://localhost:8081');
await page.getByRole('button',{name:/^금리가 오르면/}).waitFor();
await page.screenshot({path:out+'home-common.png'});
const bell=page.getByRole('button',{name:'Notifications',exact:true});
const box=await bell.boundingBox();assert(box.width>=48&&box.height>=48);
await bell.click();await page.getByRole('dialog',{name:'Notifications'}).waitFor();
await page.screenshot({path:out+'notice.png'});
await page.getByRole('button',{name:'Got it'}).click();
await page.getByRole('dialog').waitFor({state:'hidden'});
await page.setViewportSize({width:320,height:740});
await page.screenshot({path:out+'home-common-320.png'});
assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
assert.deepEqual(errors,[]);await writeFile(out+'browser.json',JSON.stringify({viewport:'393x759 app region; source 393x852 excluding OS 59 top/34 bottom',touch:box,errors,passed:['notification open/close','320 overflow']},null,2));
await browser.close();
