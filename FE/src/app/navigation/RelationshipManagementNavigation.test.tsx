import { act, fireEvent, render, screen, userEvent } from '@testing-library/react-native';
import { SafeAreaProvider } from 'react-native-safe-area-context';
import { mockUserA, mockUserB } from '../../features/auth/data/mockUsers';
import { AppNavigator } from './AppNavigator';
import { createMockAuthSource } from '../../features/auth/data/createMockAuthSource';
import { createMockDirectorySource } from '../../features/community/DirectoryProvider';
import { createMockRelationshipSource } from '../../features/community/data/createMockRelationshipSource';
import { createMockModerationSource } from '../../features/moderation/data/createMockModerationSource';

beforeEach(() => jest.useFakeTimers());
afterEach(() => jest.useRealTimers());
const button = (name: string) => screen.getByRole('button', { name });
const tab = (name: string) => screen.getByRole('tab', { name });
const flush = () => act(async () => { await jest.advanceTimersByTimeAsync(700); });

it('차단된 작성자도 Following에서 해제하며 차단·음소거는 각각의 관리 목록에 유지한다', async () => {
  let allowed = true;
  const relationships = createMockRelationshipSource({ delay: 0, canFollow: () => allowed });
  const moderation = createMockModerationSource({ delay: 0 });
  const seed = async () => {
    const follow = relationships.set(mockUserA.id, { operationId: 'follow',
      relationship: { target: { kind: 'writer', id: mockUserB.id }, following: true, email: true } });
    await jest.runOnlyPendingTimersAsync(); await follow;
    const mute = moderation.execute(mockUserA.id, { operationId: 'mute', action: { kind: 'mute', target: { kind: 'writer', id: mockUserB.id }, active: true } });
    await jest.runOnlyPendingTimersAsync(); await mute;
    const block = moderation.execute(mockUserA.id, { operationId: 'block', action: { kind: 'block', writerId: mockUserB.id, active: true } });
    await jest.runOnlyPendingTimersAsync(); await block;
    allowed = false;
  };
  await seed();
  const user = userEvent.setup({ advanceTimers: jest.advanceTimersByTime });
  await render(<SafeAreaProvider><AppNavigator initialUser={mockUserA} relationshipSource={relationships} moderationSource={moderation} /></SafeAreaProvider>);
  await user.press(tab('프로필'));
  await flush();
  await user.press(button('My following'));
  await flush();
  await user.press(button(`Unfollow ${mockUserB.name}`));
  await flush();
  expect(screen.getByText('You aren’t following anyone yet.')).toBeVisible();
  await user.press(button('Back from connections'));
  expect(button('My following')).toHaveTextContent('0 following');
  await user.press(button('설정 열기'));
  await user.press(button('Refine recommendations'));
  await user.press(tab('Muted'));
  await flush();
  expect(button(`Unmute ${mockUserB.name}`)).toBeVisible();
  await user.press(button('Back from refine recommendations'));
  await user.press(button('Account'));
  await user.press(button('Blocked users'));
  await flush();
  expect(button(`Unblock ${mockUserB.name}`)).toBeVisible();
  const value = relationships.read(mockUserA.id);
  await flush();
  expect((await value).relationships[0]).toMatchObject({ following: false, email: false });
}, 30000);

it('검색에서 팔로우한 동적 사용자를 내 Following과 추천 관리에서 열고 해제한다', async () => {
  const user = userEvent.setup({ advanceTimers: jest.advanceTimersByTime });
  const view = await render(<SafeAreaProvider><AppNavigator initialUser={mockUserA} /></SafeAreaProvider>);
  await user.press(tab('탐색'));
  await user.press(button('기사 검색 열기'));
  await fireEvent.changeText(screen.getByLabelText('기사 검색어'), mockUserB.name);
  await user.press(tab('People'));
  await flush();
  await user.press(button(`Follow ${mockUserB.name}`));
  await flush();
  await user.press(button(`Following ${mockUserB.name} options 닫기`));
  await user.press(tab('프로필'));
  await flush();
  expect(button('My following')).toHaveTextContent('1 following');
  await user.press(button('My following'));
  await flush();
  expect(button(`Following ${mockUserB.name}`)).toBeVisible();
  await view.rerender(<SafeAreaProvider><AppNavigator initialUser={mockUserA}
    directorySource={createMockDirectorySource({ delay: 0 })} /></SafeAreaProvider>);
  await flush();
  expect(button(`Following ${mockUserB.name}`)).toBeVisible();
  await user.press(button(`Discover ${mockUserB.name}`));
  await flush();
  expect(screen.getByRole('heading', { name: mockUserB.name })).toBeVisible();
  await user.press(button('Back from profile'));
  await user.press(button('Back from connections'));
  await user.press(button('설정 열기'));
  await user.press(button('Refine recommendations'));
  await flush();
  expect(screen.getByRole('heading', { name: 'Writers (1)' })).toBeVisible();
  await user.press(button('See all Writers (1)'));
  await user.press(button(`Following ${mockUserB.name}`));
  await user.press(button(`Unfollow ${mockUserB.name}`));
  await flush();
  expect(screen.getByText("You don't follow anything yet.")).toBeVisible();
  await user.press(button('Back from refine recommendations'));
  await user.press(button('프로필로 돌아가기'));
  expect(button('My following')).toHaveTextContent('0 following');
}, 30000);

it('동적 B의 이름 변경과 A→B→A 전환 뒤 차단·음소거·팔로우를 같은 ID로 각각 해제한다', async () => {
  const user = userEvent.setup({ advanceTimers: jest.advanceTimersByTime });
  await render(<SafeAreaProvider><AppNavigator initialUser={mockUserA}
    authSource={createMockAuthSource({ delayMs: 0 })} /></SafeAreaProvider>);
  await user.press(tab('탐색'));
  await user.press(button('기사 검색 열기'));
  await fireEvent.changeText(screen.getByLabelText('기사 검색어'), mockUserB.name);
  await user.press(tab('People'));
  await flush();
  await user.press(button(`Discover ${mockUserB.name}`));
  await flush();
  await user.press(button(`Follow ${mockUserB.name}`));
  await flush();
  await user.press(button(`Following ${mockUserB.name} options 닫기`));
  await user.press(button(`${mockUserB.name} options`));
  await user.press(button('Mute author'));
  await user.press(button('Confirm Mute author'));
  await flush();
  await user.press(button(`${mockUserB.name} options`));
  await user.press(button('Block author'));
  await user.press(button('Confirm Block author'));
  await flush();
  await user.press(button('Back from profile'));
  await user.press(tab('프로필'));
  await flush();
  const switchAccount = async (name: string) => {
    await user.press(button('로그아웃'));
    await user.press(button('로그아웃 확인'));
    await flush();
    await user.press(button('모의 로그인 시작'));
    await user.press(screen.getByRole('radio', { name }));
    await user.press(button('Google로 로그인 (모의)'));
    await flush();
  };
  await switchAccount(mockUserB.name);
  expect(button('My following')).toHaveTextContent('0 following');
  await user.press(button('프로필 편집'));
  await fireEvent.changeText(screen.getByLabelText('이름 · 필수'), '바뀐 독자 B');
  await fireEvent.changeText(screen.getByLabelText('짧은 소개'), '같은 ID의 공개 소개');
  await user.press(button('프로필 저장'));
  await flush();
  await switchAccount(mockUserA.name);
  expect(button('My following')).toHaveTextContent('1 following');
  await user.press(button('설정 열기'));
  await user.press(button('Account'));
  await user.press(button('Blocked users'));
  await flush();
  await user.press(button('Unblock 바뀐 독자 B'));
  await user.press(button('Cancel moderation change'));
  expect(button('Unblock 바뀐 독자 B')).toBeVisible();
  await user.press(button('Unblock 바뀐 독자 B'));
  await user.press(button('Confirm Unblock author'));
  await flush();
  expect(screen.getByText('No blocked users')).toBeVisible();
  await user.press(button('Close blocked users'));
  await user.press(button('Account에서 뒤로'));
  await user.press(button('Refine recommendations'));
  await user.press(tab('Muted'));
  await flush();
  expect(screen.getByText('같은 ID의 공개 소개')).toBeVisible();
  await user.press(button('Unmute 바뀐 독자 B'));
  await user.press(button('Confirm Unmute 바뀐 독자 B?'));
  await flush();
  expect(screen.getByText('You haven’t muted anyone.')).toBeVisible();
  await user.press(tab('Following'));
  await user.press(button('Following 바뀐 독자 B'));
  await user.press(button('Unfollow 바뀐 독자 B'));
  await flush();
  expect(screen.getByText("You don't follow anything yet.")).toBeVisible();
}, 30000);
